#!/usr/bin/env python3
"""The base of the audit records: what Lean and Mathlib depend on.

  python3 ci/audit_base.py generate   # after a toolchain, Mathlib or import change
  python3 ci/audit_base.py check      # CI (static): the generated files are current

The emitter's audit (`TCB/AuditRecords.lean`) reads what a constant of this project
depends on from records each module writes; for the constants of Lean and of its
dependencies (Mathlib and what it requires), which write none, it reads
`lean/VerifiedGarbage/TCB/AuditBase.lean`: the constants that depend on an axiom
other than `propext`, `Classical.choice` and `Quot.sound`, with those axioms. Every
other constant of theirs depends on those three at most.

That file is trusted data, generated here from the private data (`.olean.private`) of
every module of Lean and its dependencies that a file of this project imports, and
checked by `lean/VerifiedGarbageAuditBase.lean`, which `lake build` builds (the
`AuditBase` library): it imports the same modules, computes the same list, and fails
unless it is the one in `TCB/AuditBase.lean`, which it holds a copy of. Lake rebuilds
it only when what it imports changes (a toolchain or Mathlib update), or the list.

`generate` writes both files; `check` fails unless the imports of the second are those
of this project now and its copy of the list is the first's (so that its build
checks the list the records use).
"""

import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEAN = ROOT / "lean"
DATA = LEAN / "VerifiedGarbage/TCB/AuditBase.lean"
CHECK = LEAN / "VerifiedGarbageAuditBase.lean"
PROJECT = ("VerifiedGarbage", "VerifiedGarbageTest", "VerifiedGarbageAuditBase")

IMPORT = re.compile(r"^(?:public\s+)?(?:meta\s+)?import\s+(?:all\s+)?([\w.]+)")


def header_imports(path):
    """The modules a Lean file's header imports."""
    out = []
    in_comment = False
    for line in path.read_text().splitlines():
        s = line.strip()
        if in_comment:
            in_comment = "-/" not in s
            continue
        if s.startswith("/-"):
            in_comment = "-/" not in s
            continue
        if not s or s.startswith("--") or s in ("module", "prelude"):
            continue
        m = IMPORT.match(s)
        if not m:
            break
        out.append(m.group(1))
    return out


def base_imports():
    """The modules of Lean and its dependencies that a file of this project imports."""
    files = [p for d in ("VerifiedGarbage", "VerifiedGarbageTest") for p in (LEAN / d).rglob("*.lean")]
    files += [p for p in LEAN.glob("*.lean") if p != CHECK]
    mods = set()
    for f in files:
        for m in header_imports(f):
            if not m.startswith(PROJECT):
                mods.add(m)
    return sorted(mods)


def name_str(components):
    """A name as `TCB/AuditBase.lean` writes it: its components joined by `.`, a
    numeric component as its digits (`VG.AuditBase.parseName` reads it back)."""
    out = []
    for c in components:
        s = str(c)
        if isinstance(c, str) and (not c or "." in c or c.isdigit() or '"' in c or "\\" in c):
            raise SystemExit(f"cannot write the name component {c!r}")
        out.append(s)
    return ".".join(out)


def render_list(entries):
    """The list, as Lean source: one entry per line."""
    lines = []
    for name, axioms in entries:
        axs = ", ".join(f'"{name_str(a)}"' for a in axioms)
        lines.append(f'  ("{name_str(name)}", #[{axs}])')
    return "#[\n" + ",\n".join(lines) + "]"


DATA_TEMPLATE = '''module

/-!
# What Lean and its dependencies depend on

**Trusted. Generated by `ci/audit_base.py`; do not edit.** The constants of Lean and
of this project's dependencies (Mathlib and what it requires) that depend on an axiom
other than `propext`, `Classical.choice` and `Quot.sound`, with those axioms (as
`Lean.collectAxioms`), among every module of theirs a file of this project imports
(transitively). Every other constant of theirs depends on those three at most.
`TCB/AuditRecords.lean` takes their axioms from here, as they write no records;
`lean/VerifiedGarbageAuditBase.lean`, which `lake build` builds, checks the list
against their private data.

A name is its components joined by `.`, a numeric component as its digits
(`parseName`).
-/

public section

namespace VG.AuditBase

/-- The name a string of `nonStandard` writes. -/
def parseName (s : String) : Lean.Name :=
  (s.splitOn ".").foldl (init := .anonymous) fun n c =>
    if !c.isEmpty && c.all Char.isDigit then .num n c.toNat! else .str n c

/-- The constants of Lean and its dependencies that depend on a non-standard axiom,
with those axioms. -/
def nonStandard : Array (String × Array String) := LIST

end VG.AuditBase
'''

CHECK_TEMPLATE = '''-- Generated by ci/audit_base.py. DO NOT EDIT.
IMPORTS

/-!
# Checking `TCB/AuditBase.lean`

**Trusted.** Imports every module of Lean and of this project's dependencies that a
file of this project imports, and fails unless the constants among them that depend
on an axiom other than `propext`, `Classical.choice` and `Quot.sound` are those, and
with those axioms, that `TCB/AuditBase.lean` lists: `expected` is a copy of its list
(`ci/audit_base.py check` keeps it one), so that Lake rebuilds this file when the list
changes. Not a module: it loads the private data of everything it imports, which it
needs to see every proof.
-/

open Lean Elab Command

namespace VG.AuditBaseCheck

def expected : Array (String × Array String) := LIST

instance : MonadEnv (StateM Environment) where
  getEnv := get
  modifyEnv := modify

/-- A name as `TCB/AuditBase.lean` writes it. -/
def render (n : Name) : String := ".".intercalate (n.components.map fun
  | .str _ s => s
  | .num _ k => toString k
  | _ => "")

elab "#assert_audit_base" : command => do
  let env ← getEnv
  let std := [``propext, ``Classical.choice, ``Quot.sound]
  let mut found : Array (String × Array String) := #[]
  for (c, _) in env.constants.toList do
    unless (env.getModuleIdxFor? c).isSome do continue
    let axs := (collectAxioms c : StateM Environment _).run' env
    let bad := axs.filter (!std.contains ·)
    unless bad.isEmpty do
      found := found.push (render c, (bad.map render).qsort (· < ·))
  found := found.qsort (fun a b => a.1 < b.1)
  if found != expected then
    let missing := found.filter (!expected.contains ·)
    let extra := expected.filter (!found.contains ·)
    throwError m!"TCB/AuditBase.lean is out of date (run `python3 ci/audit_base.py generate`):\\n\\
      not listed: {missing.toList}\\nlisted but not found: {extra.toList}"
  logInfo m!"{found.size} constants of Lean and its dependencies depend on non-standard axioms, \\
    as TCB/AuditBase.lean lists"

end VG.AuditBaseCheck

#assert_audit_base
'''


def scan(mods):
    """The list, computed by Lean from the modules' private data."""
    with tempfile.TemporaryDirectory() as tmp:
        mods_file = Path(tmp) / "mods"
        mods_file.write_text("\n".join(mods) + "\n")
        prog = Path(tmp) / "Scan.lean"
        prog.write_text(SCAN)
        out = subprocess.run(["lake", "env", "lean", "--run", str(prog), str(mods_file)], cwd=LEAN,
                             check=True, capture_output=True, text=True).stdout
    entries = json.loads(out)
    return [(name, sorted(axs, key=name_str)) for name, axs in entries]


SCAN = '''import Lean
open Lean
instance : MonadEnv (StateM Environment) where
  getEnv := get
  modifyEnv := modify
partial def comps : Name → Array Json
  | .anonymous => #[]
  | .str p s => (comps p).push (Json.str s)
  | .num p n => (comps p).push (Json.num n)
unsafe def main (args : List String) : IO UInt32 := do
  let mods := ((← IO.FS.readFile args[0]!).splitOn "\\n").filter (!·.isEmpty) |>.map String.toName
  initSearchPath (← findSysroot)
  enableInitializersExecution
  let env ← importModules (mods.toArray.map fun m => { module := m }) {} (level := .private) (loadExts := true)
  let std := [``propext, ``Classical.choice, ``Quot.sound]
  let mut out : Array Json := #[]
  for (c, _) in env.constants.toList do
    let axs := (collectAxioms c : StateM Environment _).run' env
    let bad := axs.filter (!std.contains ·)
    unless bad.isEmpty do out := out.push (Json.arr #[Json.arr (comps c), Json.arr (bad.map (Json.arr ∘ comps))])
  IO.println (Json.arr out).compress
  return 0
'''


def entry_key(e):
    return name_str(e[0])


def generate():
    mods = base_imports()
    entries = scan(mods)
    entries.sort(key=entry_key)
    rendered = render_list([(n, axs) for n, axs in entries])
    DATA.write_text(DATA_TEMPLATE.replace("LIST", rendered))
    imports = "\n".join(f"import {m}" for m in sorted(set(mods) | {"Lean"}))
    CHECK.write_text(CHECK_TEMPLATE.replace("IMPORTS", imports).replace("LIST", rendered))
    print(f"{len(entries)} constants of {len(mods)} imported modules' closure", file=sys.stderr)


def listed(text):
    m = re.search(r":= (#\[\n.*?\])\n", text, re.S)
    return m.group(1) if m else None


def check():
    ok = True
    data, chk = DATA.read_text(), CHECK.read_text()
    if listed(data) is None or listed(data) != listed(chk):
        print(f"{CHECK.relative_to(ROOT)}: its list is not {DATA.relative_to(ROOT)}'s", file=sys.stderr)
        ok = False
    want = sorted(set(base_imports()) | {"Lean"})
    have = header_imports(CHECK)
    if want != have:
        print(f"{CHECK.relative_to(ROOT)}: imports {sorted(set(have) - set(want))} that no file of this "
              f"project imports, and not {sorted(set(want) - set(have))}", file=sys.stderr)
        ok = False
    if not ok:
        sys.exit("run `python3 ci/audit_base.py generate` in a checkout with the build restored")


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("command", choices=("generate", "check"))
    args = p.parse_args()
    generate() if args.command == "generate" else check()


if __name__ == "__main__":
    main()
