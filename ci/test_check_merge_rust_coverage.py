"""Tests for the coverage merge's handling of the generated dispatchers."""

import unittest

import merge_rust_coverage

FILE = "crates/verified-garbage-asm-x86_64/src/dispatch/poly1305.rs"
TEXT = """// @generated by lean/Emit.lean. DO NOT EDIT.
/// A dispatcher.
#[inline]
pub unsafe fn vg_f_auto(state: *mut u8) {
    let cpu = verified_garbage_cpu::detected();
    if cpu.contains(crate::poly1305::VG_F_AVX2_FEATURES) {
        return unsafe { crate::poly1305::vg_f_avx2(state) };
    }
    unsafe { crate::poly1305::vg_f(state) }
}

#[inline]
pub unsafe fn vg_g_auto(state: *mut u8) {
    let cpu = verified_garbage_cpu::detected();
    unsafe { crate::poly1305::vg_g(state) }
}
"""


class Dispatchers(unittest.TestCase):
    def test_spans(self):
        self.assertEqual(merge_rust_coverage.dispatcher_spans(FILE, TEXT), [(4, 10), (13, 16)])
        self.assertEqual(merge_rust_coverage.dispatcher_spans("src/poly1305.rs", TEXT), [])
        self.assertEqual(
            merge_rust_coverage.dispatcher_spans("crates/verified-garbage-cpu/src/dispatch/x.rs", TEXT), [])

    def test_only_unreached_dispatchers_are_dropped(self):
        # `vg_f_auto` reached, but not its `_avx2` arm; `vg_g_auto` not at all.
        raw = {FILE: {4: 3, 5: 3, 6: 3, 7: 0, 9: 3, 13: 0, 14: 0, 15: 0}, "src/x.rs": {1: 0}}
        merge_rust_coverage.drop_unreached_dispatchers(
            raw, lambda f: merge_rust_coverage.dispatcher_spans(f, TEXT))
        self.assertEqual(raw, {FILE: {4: 3, 5: 3, 6: 3, 7: 0, 9: 3}, "src/x.rs": {1: 0}})


if __name__ == "__main__":
    unittest.main()
