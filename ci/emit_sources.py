#!/usr/bin/env python3
"""Writes the emitter's module drivers, audits and runners without Lean.

`Emit.lean` writes, for each target directory, a module driver and an audit
under `lean/.lake/emit/src` (the library `VGEmit` of `lean/lakefile.toml`)
and a runner under `lean/.lake/emit` (`VG.Emit.prepare`, "Drivers as modules"
in `lean/VerifiedGarbage/TCB/Emit.lean`). `lake build` builds the library, so
the files must be there before it: before the plan (`ci/lean_shards.py`
reads their imports), and before each shard's build and the assembly's,
which may not have built the trusted base that `Emit.lean --prepare` runs.
This writes the same files, byte for byte, from the same directory listing.

It is not trusted: `Emit.lean` writes them again before it emits, from
`TCB/Emit.lean`, and builds the audits of any target whose files differ.
`--check` writes nothing and fails if the files on disk are not what this
would write, which CI runs after `Emit.lean --prepare`, so that the two never
drift apart (a drift would only rebuild the audits in the emitter's step).

  emit_sources.py [--check] [LEAN]    (LEAN: `lean/`, by default)
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent / "lean"
LIB_DIR = pathlib.Path(".lake") / "emit" / "src"


def modules_under(lean: pathlib.Path, d: str) -> list[str]:
    """`VG.Emit.modulesUnder`: the modules of the `.lean` files under `d`, in
    order of their names."""
    base = lean / d
    if not base.exists():
        return []
    mods = [".".join(p.relative_to(lean).with_suffix("").parts) for p in base.rglob("*.lean")]
    return sorted(mods)


def group_of(mod: str):
    parts = mod.split(".")
    return f"{parts[2]}.{parts[3]}" if len(parts) == 5 else None


def interfaces_of(mod: str):
    parts = mod.split(".")
    if len(parts) < 2:
        return None
    rest = parts[2:]
    if len(rest) < 3:
        return None
    t = rest[-2]
    return [i + "." + t for i in rest[:-2]]


def grouped(mods: list[str], key, what: str) -> list[tuple]:
    """Groups `mods` by `key`, in first-seen order within a group, the groups
    in order of `what` of their keys (`VG.Emit.grouped`, `genericGroups`)."""
    groups: dict = {}
    order = []
    for m in mods:
        g = key(m)
        if g is None:
            raise SystemExit(f"{m} is not at {what}")
        k = tuple(g) if isinstance(g, list) else g
        if k not in groups:
            groups[k] = []
            order.append(k)
        groups[k].append(m)
    name = (lambda k: ".".join(k)) if order and isinstance(order[0], tuple) else (lambda k: k)
    return [(list(k) if isinstance(k, tuple) else k, groups[k]) for k in sorted(order, key=name)]


def list_of(mod: str) -> str:
    return "VG." + mod.removeprefix("VerifiedGarbage.") + ".artifacts"


def variant_of(mod: str) -> str:
    return "VG." + mod.removeprefix("VerifiedGarbage.") + ".variant"


def var_name(i: int) -> str:
    return "v" if i == 0 else f"v{i + 1}"


def instances(gens: list[str], vars_: list[list[str]]) -> str:
    """`VG.Emit.instances`."""
    names = [var_name(i) for i in range(len(vars_))]
    body = "List.flatten [" + ", ".join(list_of(g) + "".join(" " + n for n in names) for g in gens) + "]"
    acc = body
    for v, ms in reversed(list(zip(names, vars_))):
        acc = f"(List.flatMap (fun {v} => {acc}) [" + ", ".join(variant_of(m) for m in ms) + "])"
    return acc


def target_dir_of(mod: str):
    parts = mod.split(".")
    if len(parts) == 4 and parts[:2] == ["VerifiedGarbage", "Artifacts"]:
        return parts[3]
    if len(parts) >= 2 and parts[0] == "VerifiedGarbage" and parts[1] in ("Generic", "Variants") \
            and len(parts) - 2 >= 3:
        return parts[-2]
    return None


def parts_of(mods, gens, vars_):
    """`VG.Emit.parts`."""
    def dir_of(m):
        t = target_dir_of(m)
        if t is None:
            raise SystemExit(f"{m} names no target directory")
        return t
    dirs = []
    for m in mods + [g for _, gs in gens for g in gs] + [v for _, vs in vars_ for v in vs]:
        t = dir_of(m)
        if t not in dirs:
            dirs.append(t)
    out = []
    for t in sorted(dirs):
        ms = [m for m in mods if dir_of(m) == t]
        gs = [(i, [g for g in g_ if dir_of(g) == t]) for i, g_ in gens]
        gs = [(i, g_) for i, g_ in gs if g_]
        vs = [(i, [v for v in v_ if dir_of(v) == t]) for i, v_ in vars_]
        vs = [(i, v_) for i, v_ in vs if v_]
        out.append((t, ms, gs, vs))
    return out


def module_driver(t, mods, gens, vars_) -> str:
    """`VG.Emit.moduleDriver`."""
    groups = [(gs, [next((ms for i2, ms in vars_ if i2 == i), []) for i in is_]) for is_, gs in gens]
    imports = mods + [g for _, gs in gens for g in gs] + [v for _, vs in vars_ for v in vs]
    return ("-- Generated by Emit.lean (`VG.Emit.moduleDriver`). DO NOT EDIT.\n"
            "module\n\n"
            "public import VerifiedGarbage.TCB.Emit\n"
            "public meta import VerifiedGarbage.TCB.Emit\n"
            + "".join(f"public import {m}\npublic meta import {m}\n" for m in imports)
            + "\n@[expose] public section\n\n"
            + f"namespace VG.Emit.{t}\n\n"
            + "def all : List Artifact := List.flatten [\n"
            + "".join(f"  {list_of(m)},\n" for m in mods)
            + "".join(f"  {instances(gs, vs)},\n" for gs, vs in groups)
            + "  []]\n\n"
            + f"end VG.Emit.{t}\n")


def audit_file(t) -> str:
    """`VG.Emit.auditFile`."""
    return ("-- Generated by Emit.lean (`VG.Emit.auditFile`). DO NOT EDIT.\n"
            "import VerifiedGarbage.TCB.Audit\n"
            "import VerifiedGarbage.TCB.Axioms\n"
            f"import VGEmit.Driver.{t}\n\n"
            f"#assert_standard_axioms VG.Emit.{t}.all\n"
            f"#assert_no_compiler_overrides VG.Emit.{t}.all VG.Emit.run\n"
            "#assert_spec_origin\n")


def runner_file(t) -> str:
    """`VG.Emit.runnerFile`."""
    return ("-- Generated by Emit.lean (`VG.Emit.runnerFile`). DO NOT EDIT.\n"
            "module\n\n"
            f"public import VGEmit.Driver.{t}\n"
            f"public meta import VGEmit.Driver.{t}\n\n"
            "public def main (args : List String) : IO UInt32 :=\n"
            f"  VG.Emit.run VG.Emit.{t}.all args\n")


def sources(lean: pathlib.Path) -> dict[pathlib.Path, str]:
    """`VG.Emit.sources` of `VG.Emit.parts`: paths relative to `lean`."""
    mods = modules_under(lean, "VerifiedGarbage/Artifacts")
    gens = grouped(modules_under(lean, "VerifiedGarbage/Generic"), interfaces_of,
                   "VerifiedGarbage/Generic/<Iface>/…/<Target>/<Name>.lean")
    vars_ = grouped(modules_under(lean, "VerifiedGarbage/Variants"), group_of,
                    "VerifiedGarbage/Variants/<Iface>/<Target>/<Name>.lean")
    files = {}
    for t, ms, gs, vs in parts_of(mods, gens, vars_):
        files[LIB_DIR / "VGEmit" / "Driver" / f"{t}.lean"] = module_driver(t, ms, gs, vs)
        files[LIB_DIR / "VGEmit" / "Audit" / f"{t}.lean"] = audit_file(t)
        files[pathlib.Path(".lake") / "emit" / f"Run{t}.lean"] = runner_file(t)
    return files


def main(argv: list[str]) -> int:
    check = "--check" in argv
    rest = [a for a in argv if a != "--check"]
    if len(rest) > 1:
        print(__doc__, file=sys.stderr)
        return 2
    lean = pathlib.Path(rest[0]) if rest else ROOT
    files = sources(lean)
    ok = True
    for rel, text in files.items():
        path = lean / rel
        current = path.read_text() if path.exists() else None
        if current == text:
            continue
        if check:
            print(f"{path} is not what ci/emit_sources.py writes", file=sys.stderr)
            ok = False
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    lib = lean / LIB_DIR
    if lib.exists():
        expected = {(lean / rel).resolve() for rel in files}
        for path in lib.rglob("*.lean"):
            if path.resolve() not in expected:
                if check:
                    print(f"{path} is not one of ci/emit_sources.py's files", file=sys.stderr)
                    ok = False
                else:
                    path.unlink()
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
